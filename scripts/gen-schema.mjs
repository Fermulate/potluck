// Snapshot the live public and private schemas into supabase/schema/current.sql.
// Functions are redefined across many migrations; this file shows the definition that is live
// after all of them. Needs the local stack, reset to this branch's migrations.
// `--check` fails when the committed snapshot differs (CI db job, `pnpm verify:db`).
import { mkdtempSync, readFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { bin, capture, repo, writeOrCheck } from './lib.mjs'

function query(sql) {
  const out = capture([
    ...bin('supabase'),
    'db',
    'query',
    '--local',
    '--agent',
    'no',
    '-o',
    'json',
    sql,
  ])
  return JSON.parse(out)
}

const dir = mkdtempSync(join(tmpdir(), 'potluck-schema-'))
try {
  const file = join(dir, 'schema.sql')
  capture([
    ...bin('supabase'),
    'db',
    'dump',
    '--local',
    '--schema',
    'public,private',
    '--file',
    file,
  ])
  const dump = readFileSync(file, 'utf8').replace(/\r\n/g, '\n').trim()
  const header = [
    '-- Generated by `pnpm gen:schema` (supabase db dump --local) after every migration ran.',
    '-- Read it to find the live definition of a table, policy or function. Do not edit it:',
    '-- write a migration, run `pnpm db:reset`, then regenerate.',
  ].join('\n')
  // The dump leaves out publications and cron jobs; list them so the snapshot is complete.
  const realtime = query(
    `select schemaname || '.' || tablename as t from pg_publication_tables
     where pubname = 'supabase_realtime' order by schemaname, tablename`,
  ).map(({ t }) => {
    const [schema, table] = t.split('.')
    return `ALTER PUBLICATION "supabase_realtime" ADD TABLE ONLY "${schema}"."${table}";`
  })
  const cron = query(`select jobname, schedule, command from cron.job order by jobname`).map(
    ({ jobname, schedule, command }) =>
      `-- cron ${jobname} '${schedule}': ${command.replace(/\s+/g, ' ').trim()}`,
  )
  const tail = [
    '--',
    '-- Realtime publication (from pg_publication_tables)',
    '--',
    '',
    ...realtime,
    '',
    '--',
    '-- pg_cron jobs (from cron.job)',
    '--',
    '',
    ...cron,
  ].join('\n')
  writeOrCheck(
    repo('supabase/schema/current.sql'),
    `${header}\n\n${dump}\n\n${tail}\n`,
    'pnpm gen:schema',
  )
} finally {
  rmSync(dir, { recursive: true, force: true })
}
